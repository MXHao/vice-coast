import test from 'node:test';
import assert from 'node:assert/strict';
import {touchCandidate} from '../tools/touch-candidate.mjs';
import {touchProjection} from '../tools/touch-fixture.mjs';
const compiled=await touchCandidate(),boot=touchProjection(compiled);
const center=(e,id)=>{const r=e.getBoundingClientRect();return {clientX:r.left+r.width/2,clientY:r.top+r.height/2,pointerId:id};};
const pos=e=>{const r=e.getBoundingClientRect();return [r.left,r.top,r.width,r.height].map(Math.round);};
function drag(el,x,y,id=21){const a=center(el,id);el.emit('pointerdown',a);el.emit('pointermove',{...a,clientX:x,clientY:y});el.emit('pointerup',{...a,clientX:x,clientY:y});}
test('compiled title → editable mock → save/reopen/cancel; walking/driving/orientation independent',()=>{
 let a=boot(),{get,panel,pick}=a;
 get('vct-title').emit('click');assert.equal(a.probe.current(),'vc-hud');
 const tok=id=>panel.querySelectorAll('button').find(e=>e.dataset.control===id);
 const defaultFire=pos(tok('touchFire'));drag(tok('touchFire'),474,187);
 pick('tool','plus');assert.ok(pos(tok('touchFire'))[2]>defaultFire[2]);
 const first=pos(tok('touchFire'));const mode=panel.querySelector('.vct-mode');
 mode.value='drive';mode.emit('change');drag(tok('gasKey'),595,240);const driving=pos(tok('gasKey'));
 pick('tool','dock');pick('tool','save');
 assert.equal(a.probe.current(),'');assert.equal(a.notes.at(-1),'触屏布局已保存');
 assert.deepEqual([...a.storage.keys()],['vc-touch-layout-v1']);assert.deepEqual(a.ops,[]);
 a.play();assert.deepEqual(pos(get('touchFire')),first);a.sync({},false);assert.deepEqual(pos(get('gasKey')),driving);
 a.tap(get('pause'));pick('action','vc-hud-open');assert.equal(panel.querySelector('.vct-mode').value,'drive');
 pick('tool','reset');assert.notDeepEqual(pos(tok('gasKey')),driving);pick('tool','cancel');
 assert.equal(a.probe.current(),'pause');assert.deepEqual(pos(get('gasKey')),driving);
 pick('action','vc-hud-open');pick('tool','reset');pick('tool','save');assert.equal(a.probe.current(),'pause');
 assert.notDeepEqual(pos(get('gasKey')),driving);a.sync(null,true);assert.deepEqual(pos(get('touchFire')),first);
 a=boot({storage:a.storage});a.play();assert.deepEqual(pos(a.get('touchFire')),first);
 a.world.w=390;a.world.h=844;a.world.safe={l:0,r:0,t:47,b:34};a.win.emit('resize');
 const tall=pos(a.get('touchFire'));assert.ok(tall[0]+tall[2]<=390&&tall[1]+tall[3]<=844-34);
 a.world.w=844;a.world.h=390;a.world.safe={l:47,r:47,t:0,b:21};a.win.emit('resize');assert.deepEqual(pos(a.get('touchFire')),first);
});
test('compiled independent native stick/look/tap shoot and simultaneous pedals/steer cancel on pause/resize',()=>{
 const a=boot(),g=a.probe.game,stick=a.get('moveStick'),cam=a.get('canvas'),fire=a.get('touchFire');a.play();
 let p=center(stick,3);stick.emit('pointerdown',p);stick.emit('pointermove',{...p,clientY:p.clientY-100});assert.ok(a.probe.axes.forward>.99);
 cam.emit('pointerdown',{pointerId:5,clientX:500,clientY:150});cam.emit('pointermove',{pointerId:5,clientX:560,clientY:165});assert.notEqual(g.walkAngle,0);
 a.tap(fire,8);assert.deepEqual(a.ops,['shot']);assert.equal(g.drag.id,5);assert.ok(a.probe.axes.forward>.99);
 cam.emit('pointercancel',{pointerId:5});stick.emit('pointercancel',{...p});assert.equal(a.probe.axes.forward,0);assert.equal(g.drag,null);
 a.sync({},false);const left=a.get('left'),gas=a.get('gasKey');left.emit('pointerdown',center(left,4));gas.emit('pointerdown',center(gas,6));
 assert.deepEqual([...a.probe.keys].sort(),['KeyA','KeyW']);gas.emit('pointerup',{pointerId:99});assert.equal(a.probe.keys.size,2);
 cam.emit('pointerdown',{pointerId:2});a.tap(a.get('pause'));assert.equal(g.paused,true);assert.equal(a.probe.keys.size,0);assert.equal(g.drag,null);
 assert.ok(!gas.hasPointerCapture(6)&&!left.hasPointerCapture(4));
 a.pick('action','vc-hud-open');
 const tok=a.panel.querySelectorAll('button').find(e=>e.dataset.control==='gasKey');
 drag(tok,500,275);assert.equal(a.probe.keys.size,0);assert.deepEqual(a.ops,['shot']);assert.equal(g.drag,null);
 a.win.emit('keydown',{code:'Escape',repeat:false});assert.equal(a.probe.current(),'pause');a.pick('action','resume');assert.equal(g.paused,false);
 const brake=a.get('brakeKey'),hb=a.get('touchBrake');brake.emit('pointerdown',center(brake,7));hb.emit('pointerdown',center(hb,8));
 assert.deepEqual([...a.probe.keys].sort(),['KeyS','Space']);a.win.emit('resize');assert.equal(a.probe.keys.size,0);
 a.tap(a.get('touchCar'));a.tap(a.get('interact'));a.sync(null,true);a.tap(a.get('touchReload'));a.tap(a.get('touchCrouch'));a.tap(a.get('touchGun'));assert.equal(g.crouched,true);
 assert.deepEqual(a.ops,['shot','car','interact','reload','equip']);
});
